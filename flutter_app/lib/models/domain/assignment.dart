import 'dart:math' as math;

/// HALL ASSIGNMENT (pure logic). Each person works through the session's hall pool as a "lottery
/// draw": a hall already visited in their current rotation cycle is an R1 repeat. All staff of a
/// session are assigned together by a minimum-cost perfect matching (Hungarian algorithm), so one
/// invigilator per hall and one hall per invigilator hold by construction. A seeded pseudo-random
/// draw per (person, hall) decides among otherwise equal choices. Ported unchanged from the Electron
/// app (shared/assignment.ts), including the cyrb53 draw, so the same input gives the same result.

class HallAssignment {
  final int userId, hallId;
  final bool isAutoGenerated;
  const HallAssignment(this.userId, this.hallId, {this.isAutoGenerated = true});
}

class AssignmentResult {
  final List<HallAssignment> entries;
  final int unavoidableRepeats;
  const AssignmentResult(this.entries, this.unavoidableRepeats);
}

/// A staff member's confirmed halls, most recent first.
typedef HallHistory = List<int> Function(int userId);

/// Whether a person handles a subject written in a hall this session.
typedef SubjectConflict = bool Function(int userId, int hallId);

const _r1Penalty = 1000000000.0;
const _lastHallPenalty = 1000000.0;

/// Halls of [pool] the person has visited in their current rotation cycle ([history] most recent first).
Set<int> visitedThisCycle(List<int> history, List<int> pool) {
  final inPool = pool.toSet();
  final visited = <int>{};
  for (var i = history.length - 1; i >= 0; i--) {
    if (!inPool.contains(history[i])) continue;
    visited.add(history[i]);
    if (visited.length == inPool.length) visited.clear();
  }
  return visited;
}

/// Seed for one generation: same batch, session and selection => same draw.
String allocationSeed({int? cycleId, required int sessionId, String? createdAt, required List<int> userIds, required List<int> hallIds}) {
  String sorted(List<int> a) => ([...a]..sort()).join(',');
  return '${cycleId ?? ''}|$sessionId|${createdAt ?? ''}|${sorted(userIds)}|${sorted(hallIds)}';
}

AssignmentResult assignHalls(List<int> userIds, List<int> hallIds, HallHistory historyOf, [String seed = '', SubjectConflict? conflictOf]) {
  if (userIds.length != hallIds.length) {
    throw StateError('Staff count (${userIds.length}) must equal hall count (${hallIds.length})');
  }
  final n = hallIds.length;
  if (n == 0) return const AssignmentResult([], 0);
  final backToBack = (n + 1).toDouble();
  final visitStep = (2 * (n + 1)).toDouble();

  final histories = userIds.map(historyOf).toList();
  final visitedSets = histories.map((h) => visitedThisCycle(h, hallIds)).toList();
  final cost = List.generate(n, (i) {
    final history = histories[i];
    final last = history.isEmpty ? null : history.first;
    final visits = <int, int>{};
    for (final h in history) {
      visits[h] = (visits[h] ?? 0) + 1;
    }
    return List.generate(n, (j) {
      final hallId = hallIds[j];
      final draw = pairDraw(seed, userIds[i], hallId);
      if (visitedSets[i].contains(hallId)) return _r1Penalty + (hallId == last ? _lastHallPenalty : 0) + draw;
      return (visits[hallId] ?? 0) * visitStep + (hallId == last ? backToBack : 0) + draw;
    });
  });

  // Subject clashes cost more than all other non-R1 costs together; an R1 repeat costs more than all clashes.
  final conflicts = conflictOf == null ? null : [for (final u in userIds) [for (final h in hallIds) conflictOf(u, h)]];
  if (conflicts != null && conflicts.any((row) => row.any((x) => x))) {
    double rest(int i, int j) => cost[i][j] - (visitedSets[i].contains(hallIds[j]) ? _r1Penalty : 0);
    var sum = 0.0;
    for (var i = 0; i < n; i++) {
      var mx = double.negativeInfinity;
      for (var j = 0; j < n; j++) {
        mx = math.max(mx, rest(i, j));
      }
      sum += mx;
    }
    final subjectPenalty = sum.ceilToDouble() + 1;
    final repeat = subjectPenalty * (n + 1);
    final next = List.generate(n, (i) => List.generate(n, (j) => rest(i, j) + (visitedSets[i].contains(hallIds[j]) ? repeat : 0) + (conflicts[i][j] ? subjectPenalty : 0)));
    for (var i = 0; i < n; i++) {
      cost[i] = next[i];
    }
  }

  final match = _hungarian(cost);
  final entries = [for (var i = 0; i < n; i++) HallAssignment(userIds[i], hallIds[match[i]])];
  var repeats = 0;
  for (var i = 0; i < n; i++) {
    if (visitedSets[i].contains(entries[i].hallId)) repeats++;
  }
  if (entries.map((e) => e.hallId).toSet().length != n || entries.map((e) => e.userId).toSet().length != n) {
    throw StateError('Allocation engine produced a duplicate hall or staff assignment (R2/R3).');
  }
  final minimum = n - _maxValidMatching(visitedSets, hallIds);
  if (repeats > minimum) throw StateError('Allocation engine produced $repeats R1 repeat(s); the minimum possible is $minimum.');
  return AssignmentResult(entries, repeats);
}

/// Minimum number of R1 repeats any assignment of these staff to these halls must contain.
int minimumRepeats(List<int> userIds, List<int> hallIds, HallHistory historyOf) {
  if (userIds.length != hallIds.length || userIds.isEmpty) return 0;
  final visited = userIds.map((u) => visitedThisCycle(historyOf(u), hallIds)).toList();
  return userIds.length - _maxValidMatching(visited, hallIds);
}

int _maxValidMatching(List<Set<int>> visitedSets, List<int> hallIds) {
  final owner = List<int>.filled(hallIds.length, -1);
  bool tryAssign(int i, List<bool> seen) {
    for (var j = 0; j < hallIds.length; j++) {
      if (seen[j] || visitedSets[i].contains(hallIds[j])) continue;
      seen[j] = true;
      if (owner[j] == -1 || tryAssign(owner[j], seen)) {
        owner[j] = i;
        return true;
      }
    }
    return false;
  }

  var matched = 0;
  for (var i = 0; i < visitedSets.length; i++) {
    if (tryAssign(i, List<bool>.filled(hallIds.length, false))) matched++;
  }
  return matched;
}

const _mask32 = 0xFFFFFFFF;
int _imul(int a, int b) => (a * b) & _mask32;

/// Pseudo-random number in [0, 1) for one (person, hall) pair (cyrb53, identical to the JS version).
double pairDraw(String seed, int userId, int hallId) {
  final str = '$seed#$userId#$hallId';
  var h1 = 0xdeadbeef, h2 = 0x41c6ce57;
  for (var i = 0; i < str.length; i++) {
    final ch = str.codeUnitAt(i);
    h1 = _imul(h1 ^ ch, 2654435761);
    h2 = _imul(h2 ^ ch, 1597334677);
  }
  h1 = _imul(h1 ^ (h1 >> 16), 2246822507) ^ _imul(h2 ^ (h2 >> 13), 3266489909);
  h2 = _imul(h2 ^ (h2 >> 16), 2246822507) ^ _imul(h1 ^ (h1 >> 13), 3266489909);
  return (4294967296.0 * (2097151 & h2) + h1) / 9007199254740992.0;
}

/// Minimum-cost perfect matching on a square cost matrix (Hungarian algorithm, O(n^3)).
List<int> _hungarian(List<List<double>> cost) {
  final n = cost.length;
  final u = List<double>.filled(n + 1, 0), v = List<double>.filled(n + 1, 0);
  final p = List<int>.filled(n + 1, 0), way = List<int>.filled(n + 1, 0);
  for (var i = 1; i <= n; i++) {
    p[0] = i;
    var j0 = 0;
    final minv = List<double>.filled(n + 1, double.infinity);
    final used = List<bool>.filled(n + 1, false);
    do {
      used[j0] = true;
      final i0 = p[j0];
      var delta = double.infinity;
      var j1 = 0;
      for (var j = 1; j <= n; j++) {
        if (used[j]) continue;
        final cur = cost[i0 - 1][j - 1] - u[i0] - v[j];
        if (cur < minv[j]) {
          minv[j] = cur;
          way[j] = j0;
        }
        if (minv[j] < delta) {
          delta = minv[j];
          j1 = j;
        }
      }
      for (var j = 0; j <= n; j++) {
        if (used[j]) {
          u[p[j]] += delta;
          v[j] -= delta;
        } else {
          minv[j] -= delta;
        }
      }
      j0 = j1;
    } while (p[j0] != 0);
    do {
      final j1 = way[j0];
      p[j0] = p[j1];
      j0 = j1;
    } while (j0 != 0);
  }
  final result = List<int>.filled(n, 0);
  for (var j = 1; j <= n; j++) {
    result[p[j] - 1] = j - 1;
  }
  return result;
}
